"""Render the silver SQL files from the table specs.

    python -m silver.render           # write sql/30_silver_reference.sql and sql/40_silver_events.sql
    python -m silver.render --check   # fail if the files on disk are out of date (used by the tests)

Why generate: seven tables share the same parsing and validation rules, and a rule that is copied
by hand drifts. The output is plain, readable SQL; read it, do not edit it.

Two conventions keep the SQL runnable on both Snowflake and the local DuckDB tests:
JSON is read with ``GET_PATH(raw, 'a.b')::STRING``, and a number counts only if it is a JSON
integer, so a bad value becomes NULL (and a reject reason) instead of an error or a silent rounding.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from .spec import (
    EVENT_TOPICS,
    INT,
    REFERENCE_TABLES,
    VALID_SCHEMA_VERSIONS,
    EventTopic,
    Field,
    ReferenceTable,
)

SQL_DIR = Path(__file__).resolve().parents[1] / "sql"
DB = "{db}"
TS_FORMAT = 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"'
EVENT_LAG = "'5 minutes'"  # leaf tables; Phase 4 hands the lag to gold and these become DOWNSTREAM
HEADER = (
    "-- GENERATED by `python -m silver.render` from silver/spec.py. Do not edit by hand.\n"
    "-- Safe to run repeatedly. {db} is the database name.\n"
)


# -- small SQL builders ------------------------------------------------------------------------
def _str(path: str) -> str:
    # Only a JSON string counts. A number in a string field is "missing", not silently stringified.
    return (
        f"IFF(TYPEOF(GET_PATH(raw, '{path}')) = 'VARCHAR', GET_PATH(raw, '{path}')::STRING, NULL)"
    )


def _num(path: str) -> str:
    # Only a JSON integer counts. TRY_TO_NUMBER on the text would accept "12.50" and round it to 13.
    return (
        f"IFF(TYPEOF(GET_PATH(raw, '{path}')) = 'INTEGER', GET_PATH(raw, '{path}')::NUMBER, NULL)"
    )


def _ts(path: str) -> str:
    return f"TRY_TO_TIMESTAMP_NTZ({_str(path)}, '{TS_FORMAT}')"


def _in(values) -> str:
    return ", ".join(f"'{v}'" for v in values)


def _field_expr(f: Field) -> str:
    return _num(f"payload.{f.name}") if f.kind == INT else _str(f"payload.{f.name}")


def _indent(text: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + line if line else line for line in text.splitlines())


# -- reference track: streams, tasks and MERGE --------------------------------------------------
def _envelope_whens(types: tuple[str, ...]) -> list[str]:
    """The envelope checks every message must pass, in the order the file writer applies them."""
    return [
        "event_id IS NULL THEN 'missing_event_id'",
        "event_type IS NULL THEN 'missing_event_type'",
        "entity_id IS NULL THEN 'missing_entity_id'",
        "event_time IS NULL THEN 'bad_type_event_time'",
        "emitted_at IS NULL THEN 'bad_type_emitted_at'",
        "schema_version IS NULL THEN 'bad_type_schema_version'",
        "sequence IS NULL THEN 'bad_type_sequence'",
        f"schema_version NOT IN ({', '.join(str(v) for v in VALID_SCHEMA_VERSIONS)}) THEN 'unknown_schema_version'",
        f"event_type NOT IN ({_in(types)}) THEN 'unknown_event_type'",
    ]


def _reference_reject_case(t: ReferenceTable) -> str:
    whens = _envelope_whens(t.event_types) + [
        "COALESCE(op, '') NOT IN ('upsert', 'delete') THEN 'bad_op'",
        f"{t.key} IS NULL THEN 'missing_payload_{t.key}'",
    ]
    required = [f for f in t.fields if f.required]
    whens += [
        f"op = 'upsert' AND {f.name} IS NULL THEN 'missing_payload_{f.name}'" for f in required
    ]
    for f in t.fields:
        if f.allowed:
            reason = "unknown_currency" if f.name == "currency" else f"bad_value_{f.name}"
            whens.append(f"op = 'upsert' AND {f.name} NOT IN ({_in(f.allowed)}) THEN '{reason}'")
    body = "\n".join(f"WHEN {w}" for w in whens)
    return "CASE\n" + _indent(body, 2) + "\nEND"


def _reference_batch(t: ReferenceTable, source: str | None = None) -> str:
    """The CTEs that read the stream (or any table of bronze rows), parse and flag bad rows."""
    source = source or f"{DB}.BRONZE.{t.bronze}_stream"
    cols = [
        f"{_str('event_id')} AS event_id",
        f"{_str('event_type')} AS event_type",
        f"{_str('entity_id')} AS entity_id",
        f"{_str('op')} AS op",
        f"{_num('schema_version')} AS schema_version",
        f"{_num('sequence')} AS sequence",
        f"{_ts('event_time')} AS event_time",
        f"{_ts('emitted_at')} AS emitted_at",
        f"{_str('payload.' + t.key)} AS {t.key}",
    ]
    cols += [f"{_field_expr(f)} AS {f.name}" for f in t.fields]
    cols += ["raw", "source_file", "source_row", "loaded_at"]
    parsed = ",\n".join("    " + c for c in cols)
    return (
        "WITH parsed AS (\n"
        "  SELECT\n"
        f"{parsed}\n"
        f"  FROM {source}\n"
        "),\n"
        "checked AS (\n"
        "  SELECT *,\n"
        f"{_indent(_reference_reject_case(t), 4)} AS reject_reason\n"
        "  FROM parsed\n"
        ")"
    )


def render_reference(t: ReferenceTable) -> str:
    attrs = [f.name for f in t.fields]
    attr_ddl = ",\n".join(f"  {a} STRING" for a in attrs)
    versions = f"{DB}.SILVER.silver_{t.name}_versions"
    current = f"{DB}.SILVER.silver_{t.name}"
    history = f"{DB}.SILVER.silver_{t.name}_history"
    rejects = f"{DB}.QUARANTINE.rejected_{t.name}"
    stream = f"{DB}.BRONZE.{t.bronze}_stream"
    proc = f"{DB}.OPS.MERGE_{t.name.upper()}"
    task = f"{DB}.OPS.MERGE_{t.name.upper()}_TASK"
    batch = _reference_batch(t)
    ver_cols = [t.key, "sequence", "event_id", "is_deleted", *attrs, "valid_from"]
    ver_cols_sql = ", ".join(ver_cols + ["loaded_at", "source_file", "source_row"])
    set_attrs = ",\n".join(f"      {a} = s.{a}" for a in attrs)
    # The row is recomputed from all versions, so a late older version can still change it (for
    # example the upsert that arrives after the delete that was merged first).
    changed = " OR ".join(
        [
            "t.last_sequence IS DISTINCT FROM s.sequence",
            "t.is_deleted IS DISTINCT FROM s.is_deleted",
        ]
        + [f"t.{a} IS DISTINCT FROM s.{a}" for a in attrs]
    )
    # A delete carries only the key. The current row takes its attributes from the newest upsert
    # and its is_deleted / sequence from the newest version, so a deleted row keeps what it was.
    latest_attrs = ", ".join(
        f"FIRST_VALUE({a}) OVER (PARTITION BY {t.key} "
        f"ORDER BY IFF(is_deleted, 1, 0), sequence DESC) AS {a}"
        for a in attrs
    )
    cur_cols = ", ".join(
        [t.key, *attrs, "is_deleted", "last_sequence", "last_event_id", "last_event_time"]
    )
    cur_vals = ", ".join(
        [
            f"s.{t.key}",
            *[f"s.{a}" for a in attrs],
            "s.is_deleted",
            "s.sequence",
            "s.event_id",
            "s.valid_from",
        ]
    )
    ver_vals = ", ".join(
        [f"s.{c}" for c in ver_cols] + ["s.loaded_at", "s.source_file", "s.source_row"]
    )
    sel_attrs = ", ".join(attrs)

    return f"""-- ---- {t.name}: stream -> MERGE (reference track) ----
CREATE TABLE IF NOT EXISTS {versions} (
  {t.key} STRING,
  sequence NUMBER,
  event_id STRING,
  is_deleted BOOLEAN,
{attr_ddl},
  valid_from TIMESTAMP_NTZ,
  loaded_at TIMESTAMP_LTZ,
  source_file STRING,
  source_row NUMBER
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS {current} (
  {t.key} STRING,
{attr_ddl},
  is_deleted BOOLEAN,
  last_sequence NUMBER,
  last_event_id STRING,
  last_event_time TIMESTAMP_NTZ
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS {rejects} (
  event_id STRING,
  entity_id STRING,
  sequence NUMBER,
  reject_reason STRING,
  raw VARIANT,
  source_file STRING,
  source_row NUMBER,
  loaded_at TIMESTAMP_LTZ,
  rejected_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- SCD2 history: one row per version, with the end of each version derived from the next one.
-- Deriving valid_to at read time means a late, out-of-order event cannot leave a stale end date.
CREATE OR REPLACE VIEW {history} AS
SELECT
  {t.key}, sequence, is_deleted, {sel_attrs}, valid_from,
  LEAD(valid_from) OVER (PARTITION BY {t.key} ORDER BY sequence) AS valid_to,
  LEAD(valid_from) OVER (PARTITION BY {t.key} ORDER BY sequence) IS NULL AS is_current
FROM {versions};

-- SHOW_INITIAL_ROWS: a stream normally starts empty. Bronze already holds rows when this is first
-- deployed, so the first run must see them too.
CREATE STREAM IF NOT EXISTS {stream} ON TABLE {DB}.BRONZE.{t.bronze}
  APPEND_ONLY = TRUE SHOW_INITIAL_ROWS = TRUE;

-- One transaction: the stream offset moves only if all three statements commit, so a failed run
-- is retried with the same changes. Every statement reads the same stream snapshot.
CREATE OR REPLACE PROCEDURE {proc}()
  RETURNS STRING
  LANGUAGE SQL
  EXECUTE AS CALLER
AS
$$
BEGIN
  BEGIN TRANSACTION;

  INSERT INTO {rejects} (event_id, entity_id, sequence, reject_reason, raw, source_file, source_row, loaded_at)
{_indent(batch, 2)}
  SELECT event_id, {t.key}, sequence, reject_reason, raw, source_file, source_row, loaded_at
  FROM checked
  WHERE reject_reason IS NOT NULL;

  MERGE INTO {versions} v
  USING (
{_indent(batch, 4)}
    SELECT {t.key}, sequence, event_id, op = 'delete' AS is_deleted, {sel_attrs},
           event_time AS valid_from, loaded_at, source_file, source_row
    FROM checked
    WHERE reject_reason IS NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY {t.key}, sequence ORDER BY loaded_at, source_file, source_row) = 1
  ) s
  ON v.{t.key} = s.{t.key} AND v.sequence = s.sequence
  WHEN NOT MATCHED THEN INSERT ({ver_cols_sql})
    VALUES ({ver_vals});

  MERGE INTO {current} t
  USING (
    SELECT {t.key}, sequence, event_id, is_deleted, {latest_attrs}, valid_from
    FROM {versions}
    QUALIFY ROW_NUMBER() OVER (PARTITION BY {t.key} ORDER BY sequence DESC) = 1
  ) s
  ON t.{t.key} = s.{t.key}
  WHEN MATCHED AND ({changed}) THEN UPDATE SET
{set_attrs},
      is_deleted = s.is_deleted,
      last_sequence = s.sequence,
      last_event_id = s.event_id,
      last_event_time = s.valid_from
  WHEN NOT MATCHED THEN INSERT ({cur_cols})
    VALUES ({cur_vals});

  COMMIT;
  RETURN 'ok';
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;

-- Created suspended. The WHEN clause means an idle stream never wakes the warehouse.
CREATE OR REPLACE TASK {task}
  WAREHOUSE = TRANSFORM_WH
  SCHEDULE = '5 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('{stream}')
AS
  CALL {proc}();
"""


# -- event track: dynamic tables -----------------------------------------------------------------
def _event_reject_case(t: EventTopic) -> str:
    whens = _envelope_whens(t.event_types) + [
        f"{t.key} IS NULL THEN 'missing_payload_{t.key}'",
    ]
    for f in t.fields:
        if f.required:
            kind = "bad_type" if f.kind == INT else "missing"
            whens.append(f"{f.name} IS NULL THEN '{kind}_payload_{f.name}'")
    for f in t.fields:
        if f.allowed:
            reason = "unknown_currency" if f.name == "currency" else f"bad_value_{f.name}"
            whens.append(f"{f.name} NOT IN ({_in(f.allowed)}) THEN '{reason}'")
    if t.amount_rule == "positive":
        whens.append("amount <= 0 THEN 'non_positive_amount'")
    elif t.amount_rule == "non_negative":
        whens.append("amount < 0 THEN 'negative_amount'")
    else:
        whens.append("amount = 0 THEN 'zero_amount'")
    body = "\n".join(f"WHEN {w}" for w in whens)
    return "CASE\n" + _indent(body, 2) + "\nEND"


def _typed_columns(t: EventTopic) -> list[str]:
    return [
        "event_id",
        "event_type",
        "entity_id",
        "schema_version",
        "sequence",
        "event_time",
        "emitted_at",
        t.key,
        *[f.name for f in t.fields],
        "source_file",
        "source_row",
        "loaded_at",
    ]


def render_typed(t: EventTopic) -> str:
    cols = [
        f"{_str('event_id')} AS event_id",
        f"{_str('event_type')} AS event_type",
        f"{_str('entity_id')} AS entity_id",
        f"{_num('schema_version')} AS schema_version",
        f"{_num('sequence')} AS sequence",
        f"{_ts('event_time')} AS event_time",
        f"{_ts('emitted_at')} AS emitted_at",
        f"{_str('payload.' + t.key)} AS {t.key}",
    ]
    cols += [f"{_field_expr(f)} AS {f.name}" for f in t.fields]
    cols += ["raw", "source_file", "source_row", "loaded_at"]
    parsed = ",\n".join("    " + c for c in cols)
    out_cols = ",\n".join("  " + c for c in _typed_columns(t))
    return f"""-- ---- {t.name}: typed layer (all rows, flagged) ----
CREATE DYNAMIC TABLE IF NOT EXISTS {DB}.SILVER.typed_{t.name}
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = TRANSFORM_WH
  REFRESH_MODE = INCREMENTAL
AS
WITH parsed AS (
  SELECT
{parsed}
  FROM {DB}.BRONZE.{t.bronze}
),
checked AS (
  SELECT *,
{_indent(_event_reject_case(t), 4)} AS reject_reason
  FROM parsed
)
SELECT
{out_cols},
  reject_reason,
  reject_reason IS NULL AS is_valid,
  -- Duplicates are counted among valid rows only: a malformed copy of a real event_id must not
  -- push the genuine event out as its "duplicate".
  ROW_NUMBER() OVER (
    PARTITION BY COALESCE(event_id, source_file || ':' || source_row::STRING), reject_reason IS NULL
    ORDER BY loaded_at, source_file, source_row
  ) AS dup_rank,
  CASE WHEN reject_reason IS NOT NULL THEN raw END AS rejected_raw
FROM checked;
"""


